function getSharedIconDriveId(data: RawAsset) {
  if (data.brand !== "Shared" || data.assetType !== "アイコン") {
    return "";
  }

  return sharedIconDriveIds[data.fileFormat]?.[data.title] ?? "";
}

type LocalMirrorManifestEntry = {
  mirrored: boolean;
  sourceDriveId: string;
  downloadPath: string;
  thumbnailPath: string;
  fileName: string;
  fileFormat: string;
};

const mirrors = rawLocalMirrorManifest as Record<string, LocalMirrorManifestEntry>;
const popularity = rawAssetPopularity as Record<string, number>;
// Call only AFTER the published projection. No complete inventory is bundled
// into browser JavaScript, and metadata never creates extra search records.
export function enrichSearchAsset(asset: CatalogAsset) {
  const driveId = asset.driveId || getDriveFileId(asset.driveUrl) || getSharedIconDriveId(asset);
  const mirror = mirrors[asset.id];
  const matchingMirror = mirror?.mirrored && (!driveId || mirror.sourceDriveId === driveId);
  const mediaUrl = (relative: string) => `/${relative.replace(/^\/+/, "")}`;
  return {
    ...asset,
    ...(driveId ? { driveId } : {}),
    ...(!asset.thumbnailUrl && matchingMirror && mirror.thumbnailPath
      ? { thumbnailUrl: mediaUrl(mirror.thumbnailPath) }
      : {}),
    ...(!asset.downloadUrl && !driveId && matchingMirror && mirror.downloadPath
      ? { downloadUrl: mediaUrl(mirror.downloadPath) }
      : {}),
    popularity: Number(popularity[asset.id] || 0),
    displayFamily: getKnownAssetFamily({ ...asset, driveId }),
  };
}
